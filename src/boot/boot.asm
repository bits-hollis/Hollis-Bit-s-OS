; ==============================================================================
; Hollis-Bit's OS — Загрузчик MBR (16-битный реальный режим BIOS)
; Загружается микропрограммой BIOS по адресу 0x7C00.
; ==============================================================================

[bits 16]
[org 0x7c00]

start:
    ; 1. Инициализация сегментов и стека
    ; Обнуляем сегментные регистры и ставим вершину стека на 0x7C00 (стек растет вниз)
    cli
    xor ax, ax
    mov ds, ax
    mov es, ax
    mov ss, ax
    mov sp, 0x7c00
    sti

    ; 2. Очистка экрана и сброс курсора через видеосервис BIOS (int 0x10)
    mov ah, 0x06        ; Функция: прокрутка/очистка экрана
    mov al, 0x00        ; 0 = очистить весь экран
    mov bh, 0x07        ; Серый текст на черном фоне
    mov cx, 0x0000      ; Верхний левый угол (0, 0)
    mov dx, 0x184f      ; Нижний правый угол (24, 79)
    int 0x10

    mov ah, 0x02        ; Установка курсора в позицию (0, 0)
    mov bh, 0x00
    mov dx, 0x0000
    int 0x10

    ; 3. Вывод приветственных сообщений на экран
    mov si, msg_hello
    call print_string
    mov si, msg_stage0
    call print_string

    ; 4. Остановка процессора до появления следующего прерывания
.halt:
    hlt
    jmp .halt

; --- Подпрограмма вывода строки (адрес в SI, конец строки — байт 0) ---
print_string:
    push ax
    push bx
.loop:
    lodsb               ; Читаем символ из [SI] в AL и двигаем указатель вперед
    or al, al           ; Если байт 0 — конец строки
    jz .done
    mov ah, 0x0e        ; Функция телетайпа BIOS: печатает символ в AL
    mov bh, 0x00
    mov bl, 0x07
    int 0x10
    jmp .loop
.done:
    pop bx
    pop ax
    ret

; --- Текстовые данные (13 = возврат каретки \r, 10 = перевод строки \n, 0 = конец) ---
msg_hello:
    db "==================================================", 13, 10
    db "       HOLLIS-BIT's OS -- GAMING SYSTEM           ", 13, 10
    db "==================================================", 13, 10, 13, 10, 0

msg_stage0:
    db "[STAGE 0] Environment & Toolchain initialized!", 13, 10
    db "[STATUS]  CPU is in 16-bit Real Mode (BIOS).", 13, 10
    db "[NEXT]    Stage 1: Load Kernel & Switch to 32-bit PM.", 13, 10, 13, 10, 0

; --- Сигнатура загрузочного сектора (ровно 512 байт с окончанием 0xAA55) ---
times 510 - ($ - $$) db 0
dw 0xAA55
